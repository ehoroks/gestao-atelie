-- DDL inicial da Trilha C para PostgreSQL/Supabase.
-- Execute manualmente no SQL Editor do Supabase SOMENTE apos alinhar nomes,
-- chaves e migracoes com as Trilhas A/B. Nao e executado automaticamente.
-- FKs para clientes/produtos/insumos ficam pendentes dos respectivos contratos.
BEGIN;

CREATE SCHEMA IF NOT EXISTS atelie;

CREATE TABLE IF NOT EXISTS atelie.composicoes_preco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL UNIQUE,
    percentual_custos_indiretos NUMERIC(10, 4) NOT NULL DEFAULT 0
        CHECK (percentual_custos_indiretos >= 0),
    margem_lucro NUMERIC(10, 4) NOT NULL DEFAULT 0
        CHECK (margem_lucro >= 0),
    preco_ajustado NUMERIC(14, 2)
        CHECK (preco_ajustado >= 0)
);

CREATE TABLE IF NOT EXISTS atelie.itens_composicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    composicao_id BIGINT NOT NULL REFERENCES atelie.composicoes_preco(id) ON DELETE CASCADE,
    insumo_id BIGINT NOT NULL,
    quantidade_usada NUMERIC(18, 4) NOT NULL CHECK (quantidade_usada > 0)
);

CREATE INDEX IF NOT EXISTS idx_itens_composicao_composicao
    ON atelie.itens_composicao(composicao_id);

CREATE TABLE IF NOT EXISTS atelie.encomendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    descricao TEXT NOT NULL CHECK (length(trim(descricao)) > 0),
    valor NUMERIC(14, 2) NOT NULL CHECK (valor >= 0),
    data_pedido DATE NOT NULL,
    previsao_entrega DATE NOT NULL CHECK (previsao_entrega >= data_pedido),
    observacoes TEXT,
    situacao VARCHAR(25) NOT NULL DEFAULT 'REGISTRADA'
        CHECK (situacao IN ('REGISTRADA', 'EM_PRODUCAO', 'PRONTA', 'ENTREGUE', 'CANCELADA'))
);

CREATE INDEX IF NOT EXISTS idx_encomendas_cliente ON atelie.encomendas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_encomendas_situacao ON atelie.encomendas(situacao);

COMMIT;
